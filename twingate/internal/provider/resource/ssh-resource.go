var (
	_ resource.Resource               = &sshResource{}
	_ resource.ResourceWithModifyPlan = &sshResource{}
)

func NewSSHResourceResource() resource.Resource {
	return &sshResource{}
}

type sshResource struct {
	baseResource
}

type sshResourceModel struct {
	pamResourceModel

	Downstream types.Object `tfsdk:"downstream"`
	Upstream   types.Object `tfsdk:"upstream"`
}

type sshPortModel struct {
	Port types.Int64 `tfsdk:"port"`
}

const defaultSSHPort = 22

var sshPortAttributeTypes = map[string]tfattr.Type{ //nolint:gochecknoglobals
	attr.Port: types.Int64Type,
}

func (r *sshResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = TwingateSSHResource
}

func (r *sshResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root(attr.ID), req, resp)

	res, err := r.client.ReadSSHResource(ctx, req.ID)
	if err != nil {
		resp.Diagnostics.AddError("failed to import state", err.Error())

		return
	}

	setImportedBaseResource(ctx, &resp.State, &resp.Diagnostics, res.BaseResource, r.defaultTags)
}

func (r *sshResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		Description: "SSH Resources are Twingate resources accessed via a Gateway.",
		Attributes: withBaseAttributes(map[string]schema.Attribute{
			attr.ID: schema.StringAttribute{
				Computed:    true,
				Description: "Autogenerated ID of the SSH Resource.",
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.UseStateForUnknown(),
				},
			},
			attr.Name: schema.StringAttribute{
				Required:    true,
				Description: "The name of the SSH Resource.",
			},
			attr.Address: schema.StringAttribute{
				Required:    true,
				Description: "The address of the SSH Resource (IP or FQDN).",
				Validators: []validator.String{
					customvalidator.Address(),
				},
			},
			attr.GatewayID: schema.StringAttribute{
				Required:    true,
				Description: "The ID of the Gateway used to access this SSH Resource.",
			},
			attr.RemoteNetworkID: schema.StringAttribute{
				Required:    true,
				Description: "The ID of the Remote Network the SSH Resource belongs to.",
			},
			attr.Downstream: sshPortAttribute("The downstream configuration. The connection between the SSH client and the Gateway."),
			attr.Upstream:   sshPortAttribute("The upstream configuration. The connection between the Gateway and the SSH server."),
		}),
		Blocks: accessBlocks(),
	}
}

// The object default covers an omitted block, since nested attribute defaults
// apply only when the parent object is configured.
func sshPortAttribute(description string) schema.SingleNestedAttribute {
	return schema.SingleNestedAttribute{
		Optional:    true,
		Computed:    true,
		Description: description,
		Default: objectdefault.StaticValue(types.ObjectValueMust(sshPortAttributeTypes, map[string]tfattr.Value{
			attr.Port: types.Int64Value(defaultSSHPort),
		})),
		Attributes: map[string]schema.Attribute{
			attr.Port: schema.Int64Attribute{
				Optional:    true,
				Computed:    true,
				Default:     int64default.StaticInt64(defaultSSHPort),
				Description: fmt.Sprintf("The port number. Must be between %d and %d inclusive. Defaults to `%d`.", model.MinPortValue, model.MaxPortValue, defaultSSHPort),
				Validators: []validator.Int64{
					int64validator.Between(model.MinPortValue, model.MaxPortValue),
				},
			},
		},
	}
}

func sshPortValue(ctx context.Context, obj types.Object, diagnostics *diag.Diagnostics) *int64 {
	if obj.IsNull() || obj.IsUnknown() {
		return nil
	}

	var port sshPortModel

	diagnostics.Append(obj.As(ctx, &port, basetypes.ObjectAsOptions{})...)

	return port.Port.ValueInt64Pointer()
}

func sshPortObject(ctx context.Context, port int64) (types.Object, diag.Diagnostics) {
	return types.ObjectValueFrom(ctx, sshPortAttributeTypes, sshPortModel{Port: types.Int64Value(port)})
}

func sshResourcePorts(ctx context.Context, plan *sshResourceModel, diagnostics *diag.Diagnostics) (*model.SSHDownstream, *model.SSHUpstream) {
	var (
		downstream *model.SSHDownstream
		upstream   *model.SSHUpstream
	)

	if port := sshPortValue(ctx, plan.Downstream, diagnostics); port != nil {
		downstream = &model.SSHDownstream{Port: *port}
	}

	if port := sshPortValue(ctx, plan.Upstream, diagnostics); port != nil {
		upstream = &model.SSHUpstream{Port: *port}
	}

	return downstream, upstream
}

func (r *sshResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan sshResourceModel

	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)

	if resp.Diagnostics.HasError() {
		return
	}

	pam, err := convertPAMResource(&plan.pamResourceModel)
	if err != nil {
		addErr(&resp.Diagnostics, err, operationCreate, TwingateSSHResource)

		return
	}

	downstream, upstream := sshResourcePorts(ctx, &plan, &resp.Diagnostics)
	if resp.Diagnostics.HasError() {
		return
	}

	sshRes, err := r.client.CreateSSHResource(ctx, &model.SSHResource{
		PAMResource: pam,
		Downstream:  downstream,
		Upstream:    upstream,
	})

	r.helper(ctx, sshRes, &plan, &resp.State, &resp.Diagnostics, err, operationCreate)
}

func (r *sshResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state sshResourceModel

	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)

	if resp.Diagnostics.HasError() {
		return
	}

	sshRes, err := r.client.ReadSSHResource(ctx, state.ID.ValueString())

	r.helper(ctx, sshRes, &state, &resp.State, &resp.Diagnostics, err, operationRead)
}

func (r *sshResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan sshResourceModel

	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)

	var state sshResourceModel

	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)

	if resp.Diagnostics.HasError() {
		return
	}

	pam, err := convertPAMResource(&plan.pamResourceModel)
	if err != nil {
		addErr(&resp.Diagnostics, err, operationUpdate, TwingateSSHResource)

		return
	}

	downstream, upstream := sshResourcePorts(ctx, &plan, &resp.Diagnostics)
	if resp.Diagnostics.HasError() {
		return
	}

	if err := updateResourceAccess(ctx, r.client, state.ID.ValueString(), convertAuthoritativeFlag(plan.IsAuthoritative), plan.accessModel, state.accessModel, baseResourceAccess(pam.BaseResource), r.readAccess(state.ID.ValueString())); err != nil {
		addErr(&resp.Diagnostics, err, operationUpdate, TwingateSSHResource)

		return
	}

	pam.ID = state.ID.ValueString()

	var sshRes *model.SSHResource

	if isSSHResourceChanged(&plan, &state) {
		sshRes, err = r.client.UpdateSSHResource(ctx, &model.SSHResource{
			PAMResource: pam,
			Downstream:  downstream,
			Upstream:    upstream,
		})
	} else {
		sshRes, err = r.client.ReadSSHResource(ctx, pam.ID)
		if sshRes != nil {
			keepPlannedAccess(&sshRes.PAMResource, pam)
		}
	}

	r.helper(ctx, sshRes, &plan, &resp.State, &resp.Diagnostics, err, operationUpdate)
}

// isSSHResourceChanged reports whether the update mutation is needed.
func isSSHResourceChanged(plan, state *sshResourceModel) bool {
	return isPAMResourceChanged(&plan.pamResourceModel, &state.pamResourceModel) ||
		!plan.Downstream.Equal(state.Downstream) ||
		!plan.Upstream.Equal(state.Upstream)
}

func (r *sshResource) readAccess(resourceID string) func(ctx context.Context) (resourceAccess, error) {
	return func(ctx context.Context) (resourceAccess, error) {
		remote, err := r.client.ReadSSHResource(ctx, resourceID)
		if err != nil {
			return resourceAccess{}, err //nolint:wrapcheck
		}

		return baseResourceAccess(remote.BaseResource), nil
	}
}

func (r *sshResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	deleteResource(ctx, req, resp, TwingateSSHResource, r.client.DeleteSSHResource)
}

func (r *sshResource) helper(ctx context.Context, sshRes *model.SSHResource, state *sshResourceModel, respState *tfsdk.State, diagnostics *diag.Diagnostics, err error, operation string) {
	if err != nil {
		if errors.Is(err, client.ErrGraphqlResultIsEmpty) {
			respState.RemoveResource(ctx)

			return
		}

		addErr(diagnostics, err, operation, TwingateSSHResource)

		return
	}

	setPAMResourceState(ctx, &state.pamResourceModel, sshRes.PAMResource, diagnostics)

	if diagnostics.HasError() {
		return
	}

	downstream, diags := sshPortObject(ctx, sshRes.Downstream.Port)
	diagnostics.Append(diags...)

	upstream, diags := sshPortObject(ctx, sshRes.Upstream.Port)
	diagnostics.Append(diags...)

	if diagnostics.HasError() {
		return
	}

	state.Downstream = downstream
	state.Upstream = upstream

	diags = respState.Set(ctx, state)
	diagnostics.Append(diags...)
}
