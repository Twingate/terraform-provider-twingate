var (
	_ resource.Resource               = &webAppResource{}
	_ resource.ResourceWithModifyPlan = &webAppResource{}
)

func NewWebAppResourceResource() resource.Resource {
	return &webAppResource{}
}

type webAppResource struct {
	baseResource
}

type webAppResourceModel struct {
	pamResourceModel

	Upstream              types.Object `tfsdk:"upstream"`
	Downstream            types.Object `tfsdk:"downstream"`
	RequestHeaderRewrites types.Map    `tfsdk:"request_header_rewrites"`
}

type webAppUpstreamModel struct {
	Port    types.Int64  `tfsdk:"port"`
	TLSMode types.String `tfsdk:"tls_mode"`
}

type webAppDownstreamModel struct {
	Port    types.Int64  `tfsdk:"port"`
	TLSMode types.String `tfsdk:"tls_mode"`
}

var webAppUpstreamAttributeTypes = map[string]tfattr.Type{ //nolint:gochecknoglobals
	attr.Port:    types.Int64Type,
	attr.TLSMode: types.StringType,
}

var webAppDownstreamAttributeTypes = map[string]tfattr.Type{ //nolint:gochecknoglobals
	attr.Port:    types.Int64Type,
	attr.TLSMode: types.StringType,
}

func (r *webAppResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = TwingateWebAppResource
}

func (r *webAppResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root(attr.ID), req, resp)

	res, err := r.client.ReadWebAppResource(ctx, req.ID)
	if err != nil {
		resp.Diagnostics.AddError("failed to import state", err.Error())

		return
	}

	setImportedBaseResource(ctx, &resp.State, &resp.Diagnostics, res.BaseResource, r.defaultTags)
}

func (r *webAppResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		Description: "Web App Resources are Twingate resources accessed via a Gateway.",
		Attributes: withBaseAttributes(map[string]schema.Attribute{
			attr.ID: schema.StringAttribute{
				Computed:    true,
				Description: "Autogenerated ID of the Web App Resource.",
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.UseStateForUnknown(),
				},
			},
			attr.Name: schema.StringAttribute{
				Required:    true,
				Description: "The name of the Web App Resource.",
			},
			attr.Address: schema.StringAttribute{
				Required:    true,
				Description: "The address of the Web App Resource (IP or FQDN).",
				Validators: []validator.String{
					customvalidator.Address(),
				},
			},
			attr.GatewayID: schema.StringAttribute{
				Required:    true,
				Description: "The ID of the Gateway used to access this Web App Resource.",
			},
			attr.RemoteNetworkID: schema.StringAttribute{
				Required:    true,
				Description: "The ID of the Remote Network the Web App Resource belongs to.",
			},
			attr.Upstream:   webAppUpstream(),
			attr.Downstream: webAppDownstream(),
			attr.RequestHeaderRewrites: schema.MapAttribute{
				ElementType: types.StringType,
				Optional:    true,
				Description: "A map of HTTP headers to rewrite on requests forwarded to the upstream resource. Header names are compared case-insensitively.",
				Validators: []validator.Map{
					customvalidator.CaseInsensitiveUniqueKeys(),
				},
			},
		}),
		Blocks: accessBlocks(),
	}
}

func webAppUpstream() schema.SingleNestedAttribute {
	return schema.SingleNestedAttribute{
		Required:    true,
		Description: "The upstream configuration. The connection between the Gateway and the upstream resource.",
		Attributes: map[string]schema.Attribute{
			attr.Port: schema.Int64Attribute{
				Required:    true,
				Description: fmt.Sprintf("The port number. Must be between %d and %d inclusive.", model.MinPortValue, model.MaxPortValue),
				Validators: []validator.Int64{
					int64validator.Between(model.MinPortValue, model.MaxPortValue),
				},
			},
			attr.TLSMode: schema.StringAttribute{
				Optional:    true,
				Computed:    true,
				Description: `How the Gateway verifies TLS on the upstream connection. One of "VERIFY_FULL", "VERIFY_CA", "INSECURE" or "NONE". Defaults to "NONE".`,
				Default:     stringdefault.StaticString(model.TLSClientModeNone),
				Validators: []validator.String{
					stringvalidator.OneOf(model.TLSClientModes...),
				},
			},
		},
	}
}

func webAppDownstream() schema.SingleNestedAttribute {
	return schema.SingleNestedAttribute{
		Required:    true,
		Description: "The downstream configuration. The connection between the protocol client and the Gateway.",
		Attributes: map[string]schema.Attribute{
			attr.Port: schema.Int64Attribute{
				Required:    true,
				Description: fmt.Sprintf("The port number. Must be between %d and %d inclusive.", model.MinPortValue, model.MaxPortValue),
				Validators: []validator.Int64{
					int64validator.Between(model.MinPortValue, model.MaxPortValue),
				},
			},
			attr.TLSMode: schema.StringAttribute{
				Optional:    true,
				Computed:    true,
				Description: `How the Gateway serves TLS on the downstream connection. One of "TLS13" or "NONE". Defaults to "NONE".`,
				Default:     stringdefault.StaticString(model.TLSServerModeNone),
				Validators: []validator.String{
					stringvalidator.OneOf(model.TLSServerModes...),
				},
			},
		},
	}
}

func webAppUpstreamValue(ctx context.Context, obj types.Object) (webAppUpstreamModel, diag.Diagnostics) {
	var upstream webAppUpstreamModel

	diags := obj.As(ctx, &upstream, basetypes.ObjectAsOptions{})

	return upstream, diags
}

func webAppDownstreamValue(ctx context.Context, obj types.Object) (webAppDownstreamModel, diag.Diagnostics) {
	var downstream webAppDownstreamModel

	diags := obj.As(ctx, &downstream, basetypes.ObjectAsOptions{})

	return downstream, diags
}

func webAppUpstreamObject(ctx context.Context, upstream model.WebAppUpstream) (types.Object, diag.Diagnostics) {
	return types.ObjectValueFrom(ctx, webAppUpstreamAttributeTypes, webAppUpstreamModel{
		Port:    types.Int64Value(upstream.Port),
		TLSMode: types.StringValue(upstream.TLSMode),
	})
}

func webAppDownstreamObject(ctx context.Context, downstream model.WebAppDownstream) (types.Object, diag.Diagnostics) {
	return types.ObjectValueFrom(ctx, webAppDownstreamAttributeTypes, webAppDownstreamModel{
		Port:    types.Int64Value(downstream.Port),
		TLSMode: types.StringValue(downstream.TLSMode),
	})
}

func (r *webAppResource) buildResource(ctx context.Context, plan *webAppResourceModel, diagnostics *diag.Diagnostics, operation string) *model.WebAppResource {
	pam, err := convertPAMResource(&plan.pamResourceModel)
	if err != nil {
		addErr(diagnostics, err, operation, TwingateWebAppResource)

		return nil
	}

	upstream, diags := webAppUpstreamValue(ctx, plan.Upstream)
	diagnostics.Append(diags...)

	downstream, diags := webAppDownstreamValue(ctx, plan.Downstream)
	diagnostics.Append(diags...)

	if diagnostics.HasError() {
		return nil
	}

	return &model.WebAppResource{
		PAMResource:           pam,
		Upstream:              model.WebAppUpstream{Port: upstream.Port.ValueInt64(), TLSMode: upstream.TLSMode.ValueString()},
		Downstream:            model.WebAppDownstream{Port: downstream.Port.ValueInt64(), TLSMode: downstream.TLSMode.ValueString()},
		RequestHeaderRewrites: getKeyValueMap(plan.RequestHeaderRewrites),
	}
}

func (r *webAppResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan webAppResourceModel

	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)

	if resp.Diagnostics.HasError() {
		return
	}

	input := r.buildResource(ctx, &plan, &resp.Diagnostics, operationCreate)
	if resp.Diagnostics.HasError() {
		return
	}

	webAppRes, err := r.client.CreateWebAppResource(ctx, input)

	r.helper(ctx, webAppRes, &plan, &resp.State, &resp.Diagnostics, err, operationCreate)
}

func (r *webAppResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state webAppResourceModel

	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)

	if resp.Diagnostics.HasError() {
		return
	}

	webAppRes, err := r.client.ReadWebAppResource(ctx, state.ID.ValueString())

	r.helper(ctx, webAppRes, &state, &resp.State, &resp.Diagnostics, err, operationRead)
}

func (r *webAppResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan webAppResourceModel

	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)

	var state webAppResourceModel

	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)

	if resp.Diagnostics.HasError() {
		return
	}

	input := r.buildResource(ctx, &plan, &resp.Diagnostics, operationUpdate)
	if resp.Diagnostics.HasError() {
		return
	}

	input.ID = state.ID.ValueString()

	if err := updateResourceAccess(ctx, r.client, input.ID, convertAuthoritativeFlag(plan.IsAuthoritative), plan.accessModel, state.accessModel, baseResourceAccess(input.BaseResource), r.readAccess(input.ID)); err != nil {
		addErr(&resp.Diagnostics, err, operationUpdate, TwingateWebAppResource)

		return
	}

	var (
		webAppRes *model.WebAppResource
		err       error
	)

	if isWebAppResourceChanged(&plan, &state) {
		webAppRes, err = r.client.UpdateWebAppResource(ctx, input)
	} else {
		webAppRes, err = r.client.ReadWebAppResource(ctx, input.ID)
		if webAppRes != nil {
			keepPlannedAccess(&webAppRes.PAMResource, input.PAMResource)
		}
	}

	r.helper(ctx, webAppRes, &plan, &resp.State, &resp.Diagnostics, err, operationUpdate)
}

// isWebAppResourceChanged reports whether the update mutation is needed.
func isWebAppResourceChanged(plan, state *webAppResourceModel) bool {
	return isPAMResourceChanged(&plan.pamResourceModel, &state.pamResourceModel) ||
		!plan.Upstream.Equal(state.Upstream) ||
		!plan.Downstream.Equal(state.Downstream) ||
		!plan.RequestHeaderRewrites.Equal(state.RequestHeaderRewrites)
}

func (r *webAppResource) readAccess(resourceID string) func(ctx context.Context) (resourceAccess, error) {
	return func(ctx context.Context) (resourceAccess, error) {
		remote, err := r.client.ReadWebAppResource(ctx, resourceID)
		if err != nil {
			return resourceAccess{}, err //nolint:wrapcheck
		}

		return baseResourceAccess(remote.BaseResource), nil
	}
}

func (r *webAppResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	deleteResource(ctx, req, resp, TwingateWebAppResource, r.client.DeleteWebAppResource)
}

func (r *webAppResource) helper(ctx context.Context, webAppRes *model.WebAppResource, state *webAppResourceModel, respState *tfsdk.State, diagnostics *diag.Diagnostics, err error, operation string) {
	if err != nil {
		if errors.Is(err, client.ErrGraphqlResultIsEmpty) {
			respState.RemoveResource(ctx)

			return
		}

		addErr(diagnostics, err, operation, TwingateWebAppResource)

		return
	}

	setPAMResourceState(ctx, &state.pamResourceModel, webAppRes.PAMResource, diagnostics)

	if diagnostics.HasError() {
		return
	}

	state.RequestHeaderRewrites = utils.ConvertMapValueWithReference(webAppRes.RequestHeaderRewrites, state.RequestHeaderRewrites)

	upstream, diags := webAppUpstreamObject(ctx, webAppRes.Upstream)
	diagnostics.Append(diags...)

	downstream, diags := webAppDownstreamObject(ctx, webAppRes.Downstream)
	diagnostics.Append(diags...)

	if diagnostics.HasError() {
		return
	}

	state.Upstream = upstream
	state.Downstream = downstream

	diags = respState.Set(ctx, state)
	diagnostics.Append(diags...)
}
