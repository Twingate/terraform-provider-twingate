const defaultKubernetesAddress = "kubernetes.default.svc.cluster.local"

var (
	ErrBearerTokenFileEmpty    = errors.New(`"bearer_token_file" must be set to a non-empty value when "in_cluster" is false`)
	ErrCAFileEmpty             = errors.New(`"ca_file" must be set to a non-empty value when "in_cluster" is false`)
	ErrAddressEmpty            = errors.New("address cannot be empty")
	ErrAddressCannotBeModified = errors.New("address cannot be modified when in_cluster is true (in_cluster must be set to false to modify address)")
)

var (
	_ resource.Resource               = &kubernetesResource{}
	_ resource.ResourceWithModifyPlan = &kubernetesResource{}
)

func NewKubernetesResourceResource() resource.Resource {
	return &kubernetesResource{}
}

type kubernetesResource struct {
	baseResource
}

type kubernetesResourceModel struct {
	pamResourceModel

	BearerTokenFile types.String `tfsdk:"bearer_token_file"`
	CAFile          types.String `tfsdk:"ca_file"`
	InCluster       types.Bool   `tfsdk:"in_cluster"`
}

func (r *kubernetesResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = TwingateKubernetesResource
}

func (r *kubernetesResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root(attr.ID), req, resp)

	res, err := r.client.ReadKubernetesResource(ctx, req.ID)
	if err != nil {
		resp.Diagnostics.AddError("failed to import state", err.Error())

		return
	}

	setImportedBaseResource(ctx, &resp.State, &resp.Diagnostics, res.BaseResource, r.defaultTags)
}

func (r *kubernetesResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		Description: "Kubernetes Resources are Twingate resources accessed via a Gateway.",
		Attributes: withBaseAttributes(map[string]schema.Attribute{
			attr.ID: schema.StringAttribute{
				Computed:    true,
				Description: "Autogenerated ID of the Kubernetes Resource.",
			},
			attr.Name: schema.StringAttribute{
				Required:    true,
				Description: "The name of the Kubernetes Resource.",
			},
			attr.Address: schema.StringAttribute{
				Optional:    true,
				Computed:    true,
				Description: "The address of the Kubernetes Resource (IP or FQDN).",
				Validators: []validator.String{
					customvalidator.Address(),
					customvalidator.HasValueWhenBoolEquals(path.Root(attr.InCluster), true, defaultKubernetesAddress),
				},
				PlanModifiers: []planmodifier.String{
					customplanmodifier.UseStringWhenBoolEquals(path.Root(attr.InCluster), true, defaultKubernetesAddress),
				},
			},
			attr.GatewayID: schema.StringAttribute{
				Required:    true,
				Description: "The ID of the Gateway used to access this Kubernetes Resource.",
			},
			attr.RemoteNetworkID: schema.StringAttribute{
				Required:    true,
				Description: "The ID of the Remote Network the Kubernetes Resource belongs to.",
			},
			attr.InCluster: schema.BoolAttribute{
				Optional:    true,
				Computed:    true,
				Description: "Whether the Gateway is running inside the same Kubernetes cluster that is represented by the Kubernetes Resource. Default is `true`.",
				Default:     booldefault.StaticBool(true),
			},
			attr.BearerTokenFile: schema.StringAttribute{
				Optional:    true,
				Computed:    true,
				Description: "Path to bearer token file. It's required when `in_cluster` is set to `false`.",
				Validators: []validator.String{
					customvalidator.NonEmptyWhenBoolEquals(path.Root(attr.InCluster), false),
				},
			},
			attr.CAFile: schema.StringAttribute{
				Optional:    true,
				Computed:    true,
				Description: "Path to CA certificate file. It's required when `in_cluster` is set to `false`.",
				Validators: []validator.String{
					customvalidator.NonEmptyWhenBoolEquals(path.Root(attr.InCluster), false),
				},
			},
		}),
		Blocks: accessBlocks(),
	}
}

func (r *kubernetesResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan kubernetesResourceModel

	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)

	if resp.Diagnostics.HasError() {
		return
	}

	address, err := kubernetesAddress(&plan)
	if err != nil {
		addErr(&resp.Diagnostics, err, operationCreate, TwingateKubernetesResource)

		return
	}

	pam, err := convertPAMResource(&plan.pamResourceModel)
	if err != nil {
		addErr(&resp.Diagnostics, err, operationCreate, TwingateKubernetesResource)

		return
	}

	pam.Address = address

	k8sRes, err := r.client.CreateKubernetesResource(ctx, &model.KubernetesResource{PAMResource: pam})

	r.helper(ctx, k8sRes, &plan, &resp.State, &resp.Diagnostics, err, operationCreate)
}

// kubernetesAddress validates the connection settings of a plan and returns the
// address to send: the fixed in-cluster address when `in_cluster` is set.
func kubernetesAddress(plan *kubernetesResourceModel) (string, error) {
	address := plan.Address.ValueString()

	if plan.InCluster.ValueBool() {
		if address != defaultKubernetesAddress && address != "" {
			return "", ErrAddressCannotBeModified
		}

		return defaultKubernetesAddress, nil
	}

	if plan.BearerTokenFile.ValueString() == "" {
		return "", ErrBearerTokenFileEmpty
	}

	if plan.CAFile.ValueString() == "" {
		return "", ErrCAFileEmpty
	}

	if address == "" {
		return "", ErrAddressEmpty
	}

	return address, nil
}

func (r *kubernetesResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state kubernetesResourceModel

	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)

	if resp.Diagnostics.HasError() {
		return
	}

	k8sRes, err := r.client.ReadKubernetesResource(ctx, state.ID.ValueString())

	r.helper(ctx, k8sRes, &state, &resp.State, &resp.Diagnostics, err, operationRead)
}

func (r *kubernetesResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan kubernetesResourceModel

	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)

	address, err := kubernetesAddress(&plan)
	if err != nil {
		addErr(&resp.Diagnostics, err, operationUpdate, TwingateKubernetesResource)

		return
	}

	var state kubernetesResourceModel

	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)

	if resp.Diagnostics.HasError() {
		return
	}

	pam, err := convertPAMResource(&plan.pamResourceModel)
	if err != nil {
		addErr(&resp.Diagnostics, err, operationUpdate, TwingateKubernetesResource)

		return
	}

	if err := updateResourceAccess(ctx, r.client, state.ID.ValueString(), convertAuthoritativeFlag(plan.IsAuthoritative), plan.accessModel, state.accessModel, baseResourceAccess(pam.BaseResource), r.readAccess(state.ID.ValueString())); err != nil {
		addErr(&resp.Diagnostics, err, operationUpdate, TwingateKubernetesResource)

		return
	}

	pam.ID = state.ID.ValueString()
	pam.Address = address

	var k8sRes *model.KubernetesResource

	if isKubernetesResourceChanged(&plan, &state, address) {
		k8sRes, err = r.client.UpdateKubernetesResource(ctx, &model.KubernetesResource{PAMResource: pam})
	} else {
		k8sRes, err = r.client.ReadKubernetesResource(ctx, pam.ID)
		if k8sRes != nil {
			keepPlannedAccess(&k8sRes.PAMResource, pam)
		}
	}

	r.helper(ctx, k8sRes, &plan, &resp.State, &resp.Diagnostics, err, operationUpdate)
}

// isKubernetesResourceChanged reports whether the update mutation is needed.
// The address is compared as it is sent: `in_cluster` replaces the planned one.
// `in_cluster`, `bearer_token_file` and `ca_file` are not sent to the API.
func isKubernetesResourceChanged(plan, state *kubernetesResourceModel, address string) bool {
	sent := plan.pamResourceModel
	sent.Address = types.StringValue(address)

	return isPAMResourceChanged(&sent, &state.pamResourceModel)
}

func (r *kubernetesResource) readAccess(resourceID string) func(ctx context.Context) (resourceAccess, error) {
	return func(ctx context.Context) (resourceAccess, error) {
		remote, err := r.client.ReadKubernetesResource(ctx, resourceID)
		if err != nil {
			return resourceAccess{}, err //nolint:wrapcheck
		}

		return baseResourceAccess(remote.BaseResource), nil
	}
}

func (r *kubernetesResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	deleteResource(ctx, req, resp, TwingateKubernetesResource, r.client.DeleteKubernetesResource)
}

func (r *kubernetesResource) helper(ctx context.Context, k8sRes *model.KubernetesResource, state *kubernetesResourceModel, respState *tfsdk.State, diagnostics *diag.Diagnostics, err error, operation string) {
	if err != nil {
		if errors.Is(err, client.ErrGraphqlResultIsEmpty) {
			respState.RemoveResource(ctx)

			return
		}

		addErr(diagnostics, err, operation, TwingateKubernetesResource)

		return
	}

	setPAMResourceState(ctx, &state.pamResourceModel, k8sRes.PAMResource, diagnostics)

	if diagnostics.HasError() {
		return
	}

	if state.InCluster.IsNull() || state.InCluster.IsUnknown() {
		state.InCluster = types.BoolValue(k8sRes.Address == defaultKubernetesAddress)
	}

	if state.BearerTokenFile.IsUnknown() {
		state.BearerTokenFile = types.StringNull()
	}

	if state.CAFile.IsUnknown() {
		state.CAFile = types.StringNull()
	}

	diags := respState.Set(ctx, state)
	diagnostics.Append(diags...)
}
